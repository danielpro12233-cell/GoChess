function posKey(fen){return fen.split(' ').slice(0,3).join(' ');}
function build(){
  book=new Map();
  var bad=[];
  var order=LINES.map(function(l,idx){return {l:l,idx:idx,n:l.slice(l.indexOf('|')+1).split(' ').length};}).sort(function(a,b){return a.n-b.n||a.idx-b.idx;});
  for(var i=0;i<order.length;i++){
    var line=order[i].l,bar=line.indexOf('|'),name=line.slice(0,bar),toks=line.slice(bar+1).split(' ');
    var pos=new E.Pos().setFen(E.START),ok=true,keys=[];
    for(var j=0;j<toks.length;j++){
      var m=E.fromSan(pos,toks[j]);
      if(!m){ok=false;bad.push(name+' @ '+toks[j]);break;}
      pos.make(m);keys.push(posKey(pos.fen()));
    }
    for(var k=0;k<keys.length;k++){
      var last=k===keys.length-1;
      if(!book.has(keys[k])||last)book.set(keys[k],name);
    }
    /* keep the valid part of a line even if a later move of it could not be read */
  }
  book.bad=bad;
  if(bad.length&&typeof console!=='undefined')console.warn('Opening book: illegal move in',bad);
}
function lookup(fen){if(!book)build();return book.get(posKey(fen))||null;}
function isBook(fen){return lookup(fen)!==null;}
function stats(){if(!book)build();return {positions:book.size,lines:LINES.length,bad:book.bad};}
